"""
Generate src/private/unicode_norm_tables.hpp from the Unicode UCD XML.

Usage:
    python -I tools/gen_unicode_tables.py <ucd.nounihan.flat.xml> <output.hpp>

Input is the "flat, no Unihan" XML from https://www.unicode.org/Public/UCD/latest/ucdxml/.
Only the standard library is needed.

Tables produced (all sorted by code point, so the C++ side can binary search):
  * canonical decompositions, fully expanded         (dt == "can")
  * compatibility decompositions, fully expanded     (every other dt except "none")
  * composition pairs: (first, second) -> composed   (one-step "can" rows, minus exclusions)
  * canonical combining classes (non-zero only)

Hangul syllables are left out on purpose. They decompose and compose by formula
(constants are emitted in the header), so listing 11,172 syllables would only bloat it.
"""

import sys
import xml.etree.ElementTree as ET

NS = "{http://www.unicode.org/ns/2003/ucd/1.0}"
HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3


def is_hangul_syllable(cp: int) -> bool:
    return HANGUL_FIRST <= cp <= HANGUL_LAST


def read_rows(path: str):
    """Return (unicode version string, {cp: (dm, dt, ccc, comp_ex)})."""
    version = None
    rows = {}
    for _, elem in ET.iterparse(path, events=("end",)):
        if elem.tag == NS + "description" and version is None:
            version = (elem.text or "").strip()
        elif elem.tag == NS + "char":
            cp = elem.get("cp")
            # Ranges (first-cp / last-cp) carry no per-character decomposition.
            if cp is not None:
                rows[int(cp, 16)] = (
                    elem.get("dm"),
                    elem.get("dt"),
                    elem.get("ccc"),
                    elem.get("Comp_Ex"),
                )
            elem.clear()
    return version, rows


def split_rows(rows):
    """One-step decompositions: (canonical, compat), each {cp: [parts]}."""
    canonical, compat = {}, {}
    for cp, (dm, dt, _, _) in rows.items():
        if dt in (None, "none") or is_hangul_syllable(cp):
            continue
        parts = [int(p, 16) for p in dm.split()]
        (canonical if dt == "can" else compat)[cp] = parts
    return canonical, compat


def expand_all(one_step: dict, follow: dict):
    """Fully expand every key of one_step, looking parts up in `follow`."""
    cache = {}

    def expand(cp: int):
        if cp in cache:
            return cache[cp]
        if cp not in follow:  # nothing left to decompose
            result = (cp,)
        else:
            result = tuple(c for part in follow[cp] for c in expand(part))
        cache[cp] = result
        return result

    return {cp: expand(cp) for cp in one_step}


def build_composition(rows):
    pairs = {}
    for cp, (dm, dt, _, comp_ex) in rows.items():
        if dt != "can" or comp_ex != "N" or is_hangul_syllable(cp):
            continue
        parts = dm.split()
        if len(parts) != 2:  # singletons are replaced, never composed into
            continue
        key = (int(parts[0], 16), int(parts[1], 16))
        assert key not in pairs, key
        pairs[key] = cp
    return pairs


def build_ccc(rows):
    return {cp: int(ccc) for cp, (_, _, ccc, _) in rows.items() if ccc not in (None, "0")}


def cp_hex(cp: int) -> str:
    return f"0x{cp:04X}"


def emit_decompositions(name: str, table: dict):
    """Sorted index first, then the flat data array it points into."""
    data, index = [], []
    for cp in sorted(table):
        index.append((cp, len(data), len(table[cp])))
        data.extend(table[cp])

    lines = [f"inline constexpr std::array<Decomposition, {len(index)}> {name}{{{{"]
    for cp, start, length in index:
        lines.append(f"    {{{cp_hex(cp)}, {start}, {length}}},")
    lines.append("}};\n")

    lines.append(f"inline constexpr std::array<char32_t, {len(data)}> {name}_DATA{{{{")
    for i in range(0, len(data), 8):
        lines.append("    " + ", ".join(cp_hex(c) for c in data[i : i + 8]) + ",")
    lines.append("}};\n")
    return "\n".join(lines)


def main(xml_path: str, out_path: str) -> None:
    version, rows = read_rows(xml_path)
    canonical_step, compat_step = split_rows(rows)

    canonical = expand_all(canonical_step, canonical_step)
    # Compatibility expansion also follows canonical rows (NFKD behaviour).
    compat = expand_all(compat_step, {**canonical_step, **compat_step})
    composition = build_composition(rows)
    ccc = build_ccc(rows)

    out = []
    out.append(f"// Generated by tools/gen_unicode_tables.py from {version}.")
    out.append("// DO NOT EDIT. Regenerate the file instead.")
    out.append("")
    out.append("#ifndef UNICODE_NORM_TABLES_HPP")
    out.append("#define UNICODE_NORM_TABLES_HPP")
    out.append("")
    out.append("#include <array>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("// clang-format off")
    out.append("namespace unicode_norm {")
    out.append("")
    out.append("// cp maps to data[start, start + length). Entries are sorted by cp.")
    out.append("struct Decomposition {")
    out.append("  char32_t cp;")
    out.append("  std::uint32_t start;")
    out.append("  std::uint8_t length;")
    out.append("};")
    out.append("")
    out.append("// first + second compose into composed. Sorted by (first, second).")
    out.append("struct Composition {")
    out.append("  char32_t first;")
    out.append("  char32_t second;")
    out.append("  char32_t composed;")
    out.append("};")
    out.append("")
    out.append("// Canonical combining class; code points not listed have class 0. Sorted by cp.")
    out.append("struct CombiningClass {")
    out.append("  char32_t cp;")
    out.append("  std::uint8_t ccc;")
    out.append("};")
    out.append("")
    out.append("// Hangul syllables are (de)composed by formula, not by table.")
    out.append("// S is for syllable.")
    out.append("// L is for leading.")
    out.append("// V is for Vowel.")
    out.append("// T is for trailing.")
    out.append("inline constexpr char32_t HANGUL_S_BASE = 0xAC00;")
    out.append("inline constexpr char32_t HANGUL_L_BASE = 0x1100;")
    out.append("inline constexpr char32_t HANGUL_V_BASE = 0x1161;")
    out.append("inline constexpr char32_t HANGUL_T_BASE = 0x11A7;")
    out.append("inline constexpr char32_t HANGUL_L_COUNT = 19;")
    out.append("inline constexpr char32_t HANGUL_V_COUNT = 21;")
    out.append("inline constexpr char32_t HANGUL_T_COUNT = 28;")
    out.append("inline constexpr char32_t HANGUL_N_COUNT = HANGUL_V_COUNT * HANGUL_T_COUNT;")
    out.append("inline constexpr char32_t HANGUL_S_COUNT = HANGUL_L_COUNT * HANGUL_N_COUNT;")
    out.append("")
    out.append("// Canonical (NFD) decompositions, fully expanded.")
    out.append(emit_decompositions("CANONICAL_DECOMPOSITIONS", canonical))
    out.append("// Compatibility (NFKD-only) decompositions, fully expanded.")
    out.append(emit_decompositions("COMPATIBILITY_DECOMPOSITIONS", compat))

    out.append("// Primary composites (NFC), without composition exclusions.")
    out.append(f"inline constexpr std::array<Composition, {len(composition)}> COMPOSITIONS{{{{")
    for (first, second), composed in sorted(composition.items()):
        out.append(f"    {{{cp_hex(first)}, {cp_hex(second)}, {cp_hex(composed)}}},")
    out.append("}};\n")

    out.append(f"inline constexpr std::array<CombiningClass, {len(ccc)}> COMBINING_CLASSES{{{{")
    for cp in sorted(ccc):
        out.append(f"    {{{cp_hex(cp)}, {ccc[cp]}}},")
    out.append("}};\n")

    out.append("} // namespace unicode_norm")
    out.append("// clang-format on")
    out.append("")
    out.append("#endif // UNICODE_NORM_TABLES_HPP")
    out.append("")

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))

    print(
        f"{version}: canonical={len(canonical)} compat={len(compat)} "
        f"composition={len(composition)} ccc={len(ccc)}"
    )


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
